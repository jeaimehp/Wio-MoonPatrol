#!/usr/bin/env python3
"""Turn the user's Moon Patrol MIDI into src/theme.h for the buzzer.

    python3 tools/midi_to_theme.py ~/Downloads/mpatrol.mid

Takes track 1, the bass line ("Dun-dun-dun-dadun..."), which is one note
at a time. Track 2 is a hi-hat, which a buzzer cannot play. Notes are
moved up two octaves: the bass sits at 82-247 Hz, too low for the piezo.
Each note is stored as its MIDI number and its length in 128 ms steps.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from midi_notes import parse  # noqa: E402

TRACK = 1
TRANSPOSE = 24
STEP_MS = 128


def main(path):
    _, _, names, notes = parse(path)
    melody = [n for n in notes if n[3] == TRACK]
    rows, t = [], 0.0
    for start, end, note, _ in melody:
        if start - t > STEP_MS / 2:
            rows.append((0, round((start - t) / STEP_MS)))  # rest
        rows.append((note + TRANSPOSE, round((end - start) / STEP_MS)))
        t = end
    out = os.path.join(os.path.dirname(__file__), "..", "src", "theme.h")
    with open(out, "w") as f:
        f.write("// Generated by tools/midi_to_theme.py from the user's mpatrol.mid,\n")
        f.write(f"// track {TRACK} ({names.get(TRACK, '')!s}), up {TRANSPOSE} semitones.\n")
        f.write("// {MIDI note (0 = rest), length in 128 ms steps}\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"static const uint16_t THEME_STEP_MS = {STEP_MS};\n")
        f.write("static const uint8_t THEME[][2] = {\n")
        for i in range(0, len(rows), 8):
            f.write("    " + " ".join(f"{{{n}, {d}}}," for n, d in rows[i:i + 8]) + "\n")
        f.write("};\n")
    total = sum(d for _, d in rows) * STEP_MS
    print(f"wrote {out}: {len(rows)} notes, {total / 1000:.1f} s")


if __name__ == "__main__":
    main(sys.argv[1])
